import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import path from 'node:path'

const commit = '5e8a3ba899557829a76cfdac30fa512bda91d7ca'
const families = [
  ['zhimangxing', 'ZhiMangXing-Regular.ttf', '行草', 'Astra Signature Zhi Mang Xing'],
  ['liujianmaocao', 'LiuJianMaoCao-Regular.ttf', '毛草', 'Astra Signature Liu Jian Mao Cao'],
  ['zcoolxiaowei', 'ZCOOLXiaoWei-Regular.ttf', '宋韵', 'Astra Signature ZCOOL XiaoWei'],
  ['zcoolkuaile', 'ZCOOLKuaiLe-Regular.ttf', '圆趣', 'Astra Signature ZCOOL KuaiLe'],
]
const assets = path.resolve('public/fonts/signature')
const evidence = path.resolve('docs/research/2026-10-07-signature-fonts')
await mkdir(evidence, { recursive: true })
const records = []
const descriptors = []
const licenses = {}
const raw = path.resolve('test-results/signature-font-acquisition')
await mkdir(raw, { recursive: true })
async function get(url, name) {
  if (process.platform === 'win32') {
    const target = path.join(raw, `${name}.json`)
    const quote = (value) => "'" + value.replaceAll("'", "''") + "'"
    execFileSync('pwsh', ['-NoProfile', '-NonInteractive', '-Command',
      `Invoke-WebRequest -Uri ${quote(url)} -OutFile ${quote(target)} -TimeoutSec 30`], { timeout: 40000 })
    return JSON.parse(await readFile(target, 'utf8'))
  }
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) })
  if (!response.ok) throw Error(`HTTP ${response.status} ${url}`)
  return response.json()
}
for (const [id, file, name, family] of families) {
  const files = []
  const entries = await get(
    `https://api.github.com/repos/google/fonts/contents/ofl/${id}?ref=${commit}`,
    id,
  )
  for (const filename of [file, 'OFL.txt']) {
    const entry = entries.find((item) => item.name === filename)
    if (!entry) throw Error(`Missing ${filename}`)
    const url = entry.git_url
    const source = await get(url, `${id}-${filename}`)
    if (source.encoding !== 'base64') throw Error('Expected base64 Git blob')
    const bytes = Buffer.from(source.content.replace(/\s/g, ''), 'base64')
    const gitSha = createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex')
    if (gitSha !== entry.sha || bytes.length !== entry.size) throw Error('Upstream hash mismatch')
    if (filename.endsWith('.ttf') && bytes.readUInt32BE(0) !== 0x00010000)
      throw Error('Not TrueType')
    const sha256 = createHash('sha256').update(bytes).digest('hex')
    await writeFile(path.join(assets, filename === 'OFL.txt' ? `${id}-OFL.txt` : file), bytes)
    files.push({ url, gitSha, sha256, bytes: bytes.length })
    if (filename === 'OFL.txt') {
      const licenseText = bytes.toString('utf8')
      if (!licenseText.includes('SIL OPEN FONT LICENSE Version 1.1')) throw Error('Missing OFL')
      licenses[id] = {
        fontSha256: files[0].sha256,
        sourceUrl: `https://github.com/google/fonts/tree/${commit}/ofl/${id}`,
        licenseText,
      }
    } else descriptors.push({ id, name, family, file, sha256 })
  }
  records.push({ id, commit, retrievedAt: new Date().toISOString(), files })
  console.log(JSON.stringify({ id, bytes: files[0].bytes, sha256: files[0].sha256 }))
}
await writeFile(path.join(evidence, 'sources.json'), JSON.stringify(records, null, 2) + '\n')
await writeFile('src/lib/signature-portrait/font-extension.ts',
  '// Pinned local OFL 1.1 fonts; generated by acquire-signature-font-extension.mjs.\n' +
  `export const SIGNATURE_FONT_EXTENSION = ${JSON.stringify(descriptors, null, 2)} as const\n` +
  `export const SIGNATURE_FONT_EXTENSION_LICENSES = ${JSON.stringify(licenses, null, 2)} as const\n`)
